export const generateGuitarChord = (
  key: string,
  type: string,
): GeneratedChord => {
  // Bemol akorları sharp karşılığına çevir
  const sharpKey = key.replace("b", "#");
  const positions = CHORDS[sharpKey]?.[type] || [];
  return { key: sharpKey, type, positions };
};

/**
 * Web kataloğu için: hangi kök ses → akor tipi kombinasyonlarının
 * gerçek basış verisi olduğunu döndürür. Sayfa üretimi buna göre yapılır,
 * böylece boş diyagramlı sayfa oluşmaz.
 */
export const GUITAR_CHORD_MAP: Record<string, string[]> = Object.fromEntries(
  Object.entries(CHORDS).map(([key, types]) => [
    key,
    Object.entries(types)
      .filter(([, positions]) => positions.length > 0)
      .map(([type]) => type),
  ]),
);
